def entry(name):
    stem = name.split(",")[0]
    if stem.startswith("horizon/"):
        stem = next(
            key for key in ("horizon/mean error", "horizon/mae", "horizon/sign") if stem.startswith(key)
        )
    label, better, definition, source = ENTRIES[stem]
    detail = name[len(stem) :].strip(" ,")
    return dict(
        family=stem.split("/")[0],
        label=label + (", " + detail if detail else ""),
        better=better,
        definition=definition,
        source=source,
    )


