async (page) => {
  const started = Date.now();
  const checks = [];
  const check = (condition,name) => { if (!condition) throw new Error(name); checks.push(name); };
  page.setDefaultTimeout(2500);
  await page.goto('http://127.0.0.1:8792/#run=search-alpha&view=trials&sort=number&dir=asc');
  await page.reload();
  await page.locator('#search').waitFor();
  await page.locator('#live').uncheck();
  await page.locator('tbody [data-trial]').first().click();
  await page.locator('#detail-tab-summary').waitFor();
  check((await page.locator('#detail-panel').innerText()).includes('-0.5'), 'Negative R squared values remain visible');
  check((await page.locator('#detail-panel').innerText()).includes('Epoch 3'), 'Epoch losses are available in the inspector');
  await page.locator('#detail-tab-summary').focus();
  await page.keyboard.press('ArrowRight');
  check(await page.locator('#detail-tab-config').getAttribute('aria-selected') === 'true', 'Detail tabs support arrow-key navigation');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('[data-action="export-trial"]').click();
  const download = await downloadPromise;
  const stream = await download.createReadStream();
  let content = '';
  for await (const chunk of stream) content += chunk;
  check(JSON.parse(content).model.hidden === 8, 'Trial export contains the exact configuration');
  await page.locator('#detail-tab-logs').click();
  check((await page.locator('#detail-panel').innerText()).includes('<unsafe & text>'), 'Worker log markup is displayed as plain text');
  await page.keyboard.press('Tab');
  check(await page.evaluate(() => Boolean(document.activeElement.closest('dialog'))), 'Keyboard focus stays inside the modal');
  await page.locator('#close-detail').click();
  await page.locator('#status').selectOption('failed');
  await page.locator('tbody [data-trial]').first().click();
  await page.locator('#detail-tab-summary').waitFor();
  check((await page.locator('#detail-panel').innerText()).includes('<img src=x onerror="alert(1)">'), 'Failure messages display untrusted markup safely');
  check(await page.locator('#detail img').count() === 0, 'Failure text cannot inject an image or event handler');
  await page.locator('#detail-tab-logs').click();
  check((await page.locator('#detail-panel').innerText()).includes('Fixture worker failure'), 'Failure traceback is available');
  await page.keyboard.press('Escape');
  await page.locator('#status').selectOption('pending');
  await page.locator('tbody [data-trial]').first().click();
  await page.locator('#detail-tab-logs').waitFor();
  await page.locator('#detail-tab-logs').click();
  check((await page.locator('#detail-panel').innerText()).includes('No worker log'), 'Trials without logs have an explicit empty state');
  await page.keyboard.press('Escape');
  await page.locator('#status').selectOption('complete');
  await page.locator('#filter-field summary').click();
  await page.locator('#filter-field-search').fill('model/view');
  await page.locator('#filter-field [data-field-choice="config/model/view"]').click();
  await page.locator('#filter-value').fill('snapshot');
  await page.getByRole('button',{name:'Add filter',exact:true}).click();
  const count = await page.locator('tbody tr').count();
  const csvPromise = page.waitForEvent('download');
  await page.locator('#export').click();
  const csv = await csvPromise;
  const csvStream = await csv.createReadStream();
  let csvText = '';
  for await (const chunk of csvStream) csvText += chunk;
  check(csvText.split('\r\n').length === count+1, 'CSV export contains exactly the filtered rows');
  check(csvText.includes('""hidden""'), 'CSV correctly escapes JSON configuration quotes');
  await page.locator('#run').selectOption('empty-run');
  await page.getByRole('heading',{name:'No trials yet',exact:true}).waitFor();
  check(await page.locator('#export').isDisabled(), 'Empty runs disable CSV export');
  await page.locator('nav [data-view="overview"]').click();
  check(await page.locator('svg').count() === 0, 'Empty runs have no invented chart data');
  await page.locator('#run').selectOption('broken-run');
  await page.locator('#error').waitFor();
  check((await page.locator('#error').innerText()).includes('unsupported run version'), 'Malformed records expose an actionable error');
  check(await page.locator('.metric').count() === 0, 'A broken run never displays the previous run metrics');
  await page.locator('#run').selectOption('search-beta');
  await page.locator('#trial-count').filter({hasText:'3'}).waitFor();
  check(await page.locator('#error').isHidden(), 'Selecting a healthy run clears the error');
  await page.locator('nav [data-view="trials"]').click();
  await page.locator('tbody [data-select]').first().check();
  await page.locator('#run').selectOption('search-alpha');
  await page.locator('#trial-count').filter({hasText:'32'}).waitFor();
  check(await page.locator('#compare-count').innerText() === '0', 'Comparison selections cannot leak into another run');
  await page.locator('.brand').click();
  check(await page.locator('#run').inputValue() === 'search-alpha', 'Brand navigation preserves the selected run');
  check(await page.locator('#page-title').innerText() === 'Analyze the search', 'Brand navigation opens the overview');
  return {checks,seconds:(Date.now()-started)/1000};
}
