async (page) => {
  const started=Date.now(), checks=[];
  const check=(condition,name)=>{if(!condition)throw new Error(name);checks.push(name);};
  const choose=async(id,field)=>{
    await page.locator(`#${id} summary`).click();
    await page.locator(`#${id}-search`).fill(field.replace('config/',''));
    await page.locator(`#${id} [data-field-choice]`).filter({hasText:field.replace('config/','')}).first().click();
  };
  page.setDefaultTimeout(3000);
  await page.goto('http://127.0.0.1:8792/#run=search-alpha&view=overview');
  await page.reload();
  await page.locator('#axis-field').waitFor();
  await page.locator('#live').uncheck();
  check(await page.locator('.metrics,.metric').count()===0,'No summary boxes exist');
  check(await page.locator('svg').count()===0,'No parameter grouping is imposed before a choice');
  check(await page.locator('#family').count()===0,'Model family is not a default filter');
  await choose('axis-field','config/graph/derive/hops');
  check((await page.locator('.analysis-heading h2').innerText()).includes('graph/derive/hops'),'Any saved parameter can drive the graph');
  const groups=await page.locator('.grouped-results tbody tr').allTextContents();
  check(groups.length===5,'Grouping includes every distinct value and missing parameters');
  const groupValues=await page.locator('.grouped-results tbody tr td:first-child').allTextContents();
  check(JSON.stringify(groupValues)===JSON.stringify(['0','2','10','100','Not used']),'Parameter groups use numeric order, not string order');
  const positions=await page.locator('circle[data-trial]').evaluateAll(nodes=>Object.fromEntries(nodes.map(node=>[node.dataset.trial,Number(node.getAttribute('cx'))])));
  check(Math.abs((positions.trial_000002-positions.trial_000000)/(positions.trial_000001-positions.trial_000000)-5)<.001,'Numeric values determine graph distance correctly');
  const raw=await (await page.request.get('http://127.0.0.1:8792/api/run?id=search-alpha')).json();
  const expectedPoints=raw.trials.filter(t=>t.status==='complete' && Object.hasOwn(t.config.graph,'derive/hops')).length;
  check(await page.locator('circle[data-trial]').count()===expectedPoints,'The graph includes every eligible completed trial');
  const csvPromise=page.waitForEvent('download');
  await page.locator('[data-action="export-groups"]').click();
  let csv='';for await(const chunk of await (await csvPromise).createReadStream())csv+=chunk;
  check(csv.split('\r\n').length===6 && csv.includes('Not used'),'Grouped export includes all values and the missing group');
  await page.locator('[data-group-value="0"]').click();
  check(await page.locator('tbody tr').count()===6,'Group drilldown shows exactly the matching trials');
  check((await page.locator('.condition-list').innerText()).includes('equals 0'),'Drilldown exposes its exact filter');
  check((await page.locator('thead').innerText()).includes('graph/derive/hops'),'Plot parameters become visible table columns');
  check(!(await page.locator('thead').innerText()).includes('Model /'),'The table does not default to model family');
  await page.locator('.filters [data-action="clear-filters"]').click();
  await choose('sort-field','config/graph/derive/hops');
  await page.locator('#sort-direction').click();
  check(await page.locator('tbody tr').first().locator('[data-column="config/graph/derive/hops"]').innerText()==='0','Parameter sort supports numeric ascending order');
  await page.locator('#sort-direction').click();
  check(await page.locator('tbody tr').first().locator('[data-column="config/graph/derive/hops"]').innerText()==='100','Parameter sort supports numeric descending order');
  await page.getByRole('button',{name:'Next page',exact:true}).click();
  check(await page.locator('tbody tr').last().locator('[data-column="config/graph/derive/hops"]').innerText()==='Not used','Missing values stay last when sorting descending');
  await choose('column-field','config/graph/derive/enabled');
  check(await page.locator('[data-sort="config/graph/derive/enabled"]').count()===1,'Boolean parameters can be added as columns');
  await choose('filter-field','config/graph/derive/hops');
  await page.locator('#filter-op').selectOption('gte');
  await page.locator('#filter-value').fill('10');
  await page.getByRole('button',{name:'Add filter',exact:true}).click();
  check(await page.locator('tbody tr').count()===14,'Numeric filters compare numbers correctly');
  await page.locator('#filter-op').selectOption('lt');
  await page.locator('#filter-value').fill('100');
  await page.getByRole('button',{name:'Add filter',exact:true}).click();
  check(await page.locator('tbody tr').count()===7,'Multiple parameter filters combine with AND');
  await page.locator('nav [data-view="overview"]').click();
  check((await page.locator('.analysis-heading p').innerText()).startsWith('7 matching trials'),'Graphs and tables share the same filters');
  await page.locator('#chart-metric').selectOption('r2');
  check((await page.locator('svg').getAttribute('aria-label')).includes('R²'),'The measured result can change independently of the parameter');
  await page.reload();
  await page.locator('.analysis-heading').waitFor();
  check((await page.locator('#axis-field-chosen').innerText())==='graph/derive/hops','Reload preserves the chosen graph parameter');
  check(await page.locator('.condition-chip').count()===2,'Reload preserves compound parameter filters');
  await page.locator('#live').uncheck();
  await page.locator('.filters [data-action="clear-filters"]').click();
  await choose('filter-field','config/graph/derive/hops');
  await page.locator('#filter-op').selectOption('missing');
  check(await page.locator('#filter-value').isDisabled(),'Presence filters do not require invented values');
  await page.getByRole('button',{name:'Add filter',exact:true}).click();
  check((await page.locator('.analysis-heading p').innerText()).startsWith('6 matching trials'),'Missing parameters can be investigated explicitly');
  check(await page.locator('circle').count()===0,'Missing parameters do not become zero on a graph');
  await page.locator('.filters [data-action="clear-filters"]').click();
  await choose('axis-field','config/graph/derive/enabled');
  check(await page.locator('.grouped-results tbody tr').count()===2,'Boolean parameters form distinct groups');
  await choose('axis-field','config/model/view');
  check(await page.locator('.grouped-results tbody tr').count()===3,'Categorical parameters are available when explicitly chosen');
  await choose('axis-field','config/lr');
  check(await page.locator('circle').count()===23,'Constant parameters still produce a usable graph');
  await page.clock.install();
  await page.locator('#live').check();
  await page.locator('#axis-field summary').click();
  await page.locator('#axis-field-search').fill('derive/hop');
  const refreshed=page.waitForResponse(response=>response.url().includes('/api/run?'));
  await page.clock.fastForward(5100);
  await refreshed;
  await page.waitForFunction(()=>!document.querySelector('#refresh').disabled);
  check(await page.locator('#axis-field').getAttribute('open')!==null,'Refresh preserves an open parameter chooser');
  check(await page.locator('#axis-field-search').inputValue()==='derive/hop','Refresh preserves chooser search text');
  await page.locator('#axis-field-search').focus();
  await page.keyboard.press('Enter');
  check(await page.locator('#axis-field-chosen').innerText()==='graph/derive/hops','A uniquely matching parameter can be chosen with Enter');
  await page.locator('#live').uncheck();
  await page.clock.resume();
  await page.locator('nav [data-view="trials"]').click();
  await page.locator('[data-remove-column]').first().click();
  check(await page.locator('[data-sort="config/graph/derive/hops"]').count()===0,'Chosen columns can be removed');
  return {checks,seconds:(Date.now()-started)/1000};
}
