async (page) => {
  const started = Date.now();
  const checks = [];
  const errors = [];
  const onError = error => errors.push(error.message);
  page.on('pageerror', onError);
  page.setDefaultTimeout(2500);
  const check = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  await page.goto('http://127.0.0.1:8792/#run=search-alpha&view=overview');
  await page.reload();
  await page.locator('#trial-count').filter({hasText:'32'}).waitFor();
  await page.locator('#live').uncheck();
  check(await page.locator('.metrics,.metric').count() === 0, 'Summary boxes are absent');
  await page.locator('#axis-field summary').click();
  await page.locator('#axis-field-search').fill('Trial order');
  await page.locator('#axis-field [data-field-choice=number]').click();
  check(await page.locator('circle[data-trial=trial_000003]').getAttribute('aria-label').then(text => text.includes(' 0')), 'A genuine zero score remains visible');
  await page.locator('#chart-metric').selectOption('r2');
  check(await page.locator('svg').getAttribute('aria-label') === 'Validation R² ↑ by Trial order', 'Metric selector updates the chart');
  check(await page.locator('circle[tabindex="0"]').count() === 1, 'Large charts occupy a single Tab stop');
  await page.locator('circle[data-trial]').first().focus();
  await page.keyboard.press('ArrowRight');
  check(await page.evaluate(() => document.activeElement.dataset.trial) === 'trial_000001', 'Chart points support arrow-key navigation');
  await page.locator('circle[data-trial]').first().focus();
  await page.keyboard.press('Enter');
  await page.locator('#detail-tab-summary').waitFor();
  check(await page.locator('#detail').isVisible(), 'Chart points open details with Enter');
  await page.keyboard.press('Escape');
  check(!await page.locator('#detail').isVisible(), 'Escape closes trial details');
  await page.locator('nav [data-view="trials"]').click();
  check(await page.locator('tbody tr').count() === 25, 'Trials are paginated at 25 rows');
  await page.getByRole('button',{name:'Next page',exact:true}).click();
  check(await page.locator('tbody tr').count() === 7, 'Final page contains remaining trials');
  await page.getByRole('button',{name:'Previous page',exact:true}).click();
  await page.locator('#status').selectOption('failed');
  check(await page.locator('tbody tr').count() === 4, 'Status filter selects only failed trials');
  await page.locator('#filter-field summary').click();
  await page.locator('#filter-field-search').fill('model/view');
  await page.locator('#filter-field [data-field-choice="config/model/view"]').click();
  await page.locator('#filter-value').fill('snapshot');
  await page.getByRole('button',{name:'Add filter',exact:true}).click();
  check(await page.locator('tbody tr').count() === 2, 'Family and status filters combine');
  await page.locator('#search').fill('not-a-real-trial');
  check(await page.getByRole('heading',{name:'No matching trials'}).isVisible(), 'Empty filter results are explicit');
  check(await page.locator('#export').isDisabled(), 'Empty results cannot produce a misleading export');
  await page.locator('.filters [data-action="clear-filters"]').click();
  await page.locator('[data-sort="mse"]').click();
  check((await page.locator('tbody tr').first().innerText()).includes('Trial 004'), 'Ascending MSE sorts zero first');
  await page.locator('[data-sort="mse"]').click();
  check((await page.locator('tbody tr').first().innerText()).includes('Trial 001'), 'Descending MSE sorts the maximum first');
  check(!(await page.locator('tbody tr').first().innerText()).includes('pending'), 'Missing metrics stay last in descending sort');
  await page.locator('#search').fill('"hidden":11');
  check(await page.locator('tbody tr').count() === 1, 'Search includes configuration values');
  await page.locator('#refresh').click();
  await page.waitForFunction(() => !document.querySelector('#refresh').disabled);
  check(await page.locator('#search').inputValue() === '"hidden":11', 'Refresh preserves the search');
  await page.reload();
  await page.locator('#search').waitFor();
  check(await page.locator('#search').inputValue() === '"hidden":11', 'Reload restores filters from the URL');
  await page.locator('#live').uncheck();
  await page.locator('.filters [data-action="clear-filters"]').click();
  for (let i=0;i<4;i++) await page.locator('tbody [data-select]').nth(i).check();
  await page.locator('tbody [data-select]').nth(4).click();
  check(await page.locator('tbody [data-select]:checked').count() === 4, 'Comparison selection is limited to four');
  check((await page.locator('#toast').innerText()).includes('up to four'), 'Selection limit explains how to proceed');
  await page.locator('#status').selectOption('timeout');
  check(await page.locator('#compare-count').innerText() === '4', 'Hidden selections persist while filtering');
  await page.locator('nav [data-view="compare"]').click();
  check(await page.locator('.compare-table thead th').count() === 5, 'Four selected trials appear side by side');
  await page.locator('#differences').check();
  check(await page.locator('.compare-table tr.different').count() > 0, 'Differing configuration rows are shown');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('[data-action="export-configs"]').click();
  const downloaded = await downloadPromise;
  const stream = await downloaded.createReadStream();
  let content = '';
  for await (const chunk of stream) content += chunk;
  check(JSON.parse(content).length === 4, 'Configuration export contains the selected trials');
  await page.locator('[data-remove]').first().click();
  check(await page.locator('#compare-count').innerText() === '3', 'Removing a comparison updates selection');
  await page.locator('[data-action="clear-selection"]').click();
  check(await page.getByRole('heading',{name:'Put the choices side by side'}).isVisible(), 'Clearing selection produces a usable empty comparison');
  check(errors.length === 0, 'No browser exceptions');
  page.off('pageerror',onError);
  return {checks, seconds:(Date.now()-started)/1000};
}
