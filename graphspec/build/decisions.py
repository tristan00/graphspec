import logging
import math
import time
from collections import Counter

import numpy as np

from graphspec.facts.stored import codes
from graphspec.infra.timing import timed
from graphspec.schema.decisions import GENERATORS, WHOLE, deciding
from graphspec.schema.time import NEVER

LOG = logging.getLogger(__name__)
FIELDS = ("key", "sequence", "available", "chosen", "order", "shown", "logged", "generator", "seed", "drawn")


@timed("decided.probability")
def probability(value):
    return value is None or (math.isfinite(value) and 0 <= value <= 1)


class Decided:
    def __init__(self, registry, tasks, members, keys, kinds, seen, name):
        started = time.perf_counter()
        schema = registry.schema
        self.registry, self.schema, self.name, self.tasks = registry, schema, name, tasks
        self.keys, self.kinds = list(keys), [int(kind) for kind in kinds]
        self.listed = list(schema.tasks["kinds"])
        self.aims = [schema.tasks["kinds"][kind]["target"] for kind in self.listed]
        owner = np.asarray(tasks["task_kind"], np.int64)
        self.deciding = np.asarray([deciding(target) for target in self.aims] + [False], bool)[owner]
        self.lookup = {(kind, key): entity for entity, (kind, key) in enumerate(zip(self.kinds, self.keys))}
        self.first = np.full(len(self.keys), NEVER, np.int64)
        np.minimum.at(self.first, np.asarray(seen["entity"], np.int64), np.asarray(seen["since"], np.int64))
        self.actors = self.acting(members)
        LOG.debug("decided exit graph=%s tasks=%d seconds=%.4f", name, len(owner), time.perf_counter() - started)

    @timed("decided.where")
    def where(self, task):
        return "the decision %d of the kind %s of graph %s" % (
            self.tasks["task_key"][task],
            self.listed[self.tasks["task_kind"][task]],
            self.name,
        )

    def acting(self, members):
        started = time.perf_counter()
        references = list(self.schema.tasks["references"])
        result = {task: {} for task in np.flatnonzero(self.deciding).tolist()}
        for task, name, source in zip(
            *(np.asarray(members[key]).tolist() for key in ("member_task", "member_name", "member_source"))
        ):
            target = self.aims[self.tasks["task_kind"][task]]
            if not deciding(target) or references[name] != target["actors"]:
                continue
            held = result[task]
            if self.keys[source] in held:
                raise ValueError("%s names two actors of the key %s" % (self.where(task), self.keys[source]))
            held[self.keys[source]] = source
        LOG.debug("decided acting exit decisions=%d seconds=%.4f", len(result), time.perf_counter() - started)
        return result

    def options(self, table, place):
        started = time.perf_counter()
        task = place[np.asarray(table.column("task").to_numpy(), np.int64)]
        order = np.argsort(task, kind="stable")
        found = {name: table.column(name).to_pylist() for name in FIELDS}
        generators, rows = [], []
        for row in order.tolist():
            owner, held = int(task[row]), {name: found[name][row] for name in FIELDS}
            where = "the option %s of %s" % (held["key"], self.where(owner))
            if not self.deciding[owner]:
                raise ValueError("%s belongs to a task whose kind states no decision" % where)
            if type(held["key"]) is not str or not held["key"]:
                raise ValueError("an option of %s states no key" % self.where(owner))
            if None in (held["sequence"], held["available"], held["chosen"]):
                raise ValueError("%s states whether its actions are a sequence, whether it was available and whether it was chosen" % where)
            if held["order"] is not None and held["order"] < 0:
                raise ValueError("%s states its order of choice as a whole number from 0, found %d" % (where, held["order"]))
            if not all(probability(held[name]) for name in ("shown", "logged", "drawn")):
                raise ValueError("%s states a probability outside 0 and 1" % where)
            if held["generator"] is None:
                if held["seed"] is not None or held["drawn"] is not None:
                    raise ValueError("%s is recorded and states a seed or the probability of a draw" % where)
                generator, seed = -1, 0
            else:
                if held["generator"] not in GENERATORS.names():
                    raise ValueError(
                        "%s is regenerated by the generator %s, which is not registered in graphspec.GENERATORS"
                        % (where, held["generator"])
                    )
                if held["seed"] is None or held["seed"] < 0:
                    raise ValueError("%s is regenerated and states its seed, a whole number from 0" % where)
                if held["chosen"]:
                    raise ValueError("%s is regenerated and chosen; an option a generator drew was never chosen" % where)
                if held["generator"] not in generators:
                    generators.append(held["generator"])
                generator, seed = generators.index(held["generator"]), held["seed"]
            rows.append(dict(held, task=owner, generator=generator, seed=seed))
        tasks = np.asarray([row["task"] for row in rows], np.int64)
        for owner in np.unique(tasks).tolist():
            self.chosen(owner, [row for row in rows if row["task"] == owner])
        result = dict(
            option_task=tasks.astype(np.int32),
            option_sequence=np.asarray([row["sequence"] for row in rows], bool).reshape(-1),
            option_available=np.asarray([row["available"] for row in rows], bool).reshape(-1),
            option_chosen=np.asarray([row["chosen"] for row in rows], bool).reshape(-1),
            option_order=np.asarray([-1 if row["order"] is None else row["order"] for row in rows], np.int32).reshape(-1),
            option_generator=np.asarray([row["generator"] for row in rows], np.int32).reshape(-1),
            option_seed=np.asarray([row["seed"] for row in rows], np.int64).reshape(-1),
            **{
                "option_" + name: np.asarray(
                    [np.nan if row[name] is None else row[name] for row in rows], np.float64
                ).reshape(-1)
                for name in ("shown", "logged", "drawn")
            },
        )
        LOG.debug("decided options exit graph=%s options=%d seconds=%.4f", self.name, len(rows), time.perf_counter() - started)
        return result, [row["key"] for row in rows], generators, order

    def chosen(self, task, rows):
        started = time.perf_counter()
        where = self.where(task)
        keys = [row["key"] for row in rows]
        if len(set(keys)) != len(keys):
            raise ValueError("%s states two options of one key" % where)
        chosen = [row for row in rows if row["chosen"]]
        if not chosen:
            raise ValueError("%s states no option chosen" % where)
        orders = sorted(row["order"] for row in chosen if row["order"] is not None)
        stray = [row["key"] for row in rows if not row["chosen"] and row["order"] is not None]
        wanted = [] if len(chosen) == 1 else list(range(len(chosen)))
        if stray or orders != wanted or (len(chosen) == 1 and chosen[0]["order"] is not None):
            raise ValueError(
                "%s states the order of choice of each of its options chosen, from 0, where several were, and of no "
                "other option" % where
            )
        LOG.debug("decided chosen exit options=%d seconds=%.4f", len(rows), time.perf_counter() - started)

    def actions(self, table, options, inverse):
        started = time.perf_counter()
        columns = self.schema.parameters()
        owner = inverse[np.asarray(table.column("option").to_numpy(), np.int64)]
        order = np.argsort(owner, kind="stable")
        values = codes(self.registry, table, columns, range(len(columns)), len(columns))
        kinds, actors = table.column("kind").to_pylist(), table.column("actor").to_pylist()
        result = dict(action_option=[], action_kind=[], action_actor=[])
        declared, places = [], Counter()
        for row in order.tolist():
            option = int(owner[row])
            task = int(options["option_task"][option])
            target, place = self.aims[self.tasks["task_kind"][task]], places[option]
            places[option] += 1
            where ="the action %d, of the kind %s, of the option %s of %s" % (
                place,
                kinds[row],
                options["keys"][option],
                self.where(task),
            )
            if kinds[row] not in target["actions"]:
                raise ValueError("%s is of a kind of action its kind of task does not state" % where)
            action = target["actions"][kinds[row]]
            if actors[row] not in self.actors[task]:
                raise ValueError("%s names the actor %s, which is not one of the actors of its decision" % (where, actors[row]))
            stray = [
                name
                for place, name in enumerate(columns)
                if name not in action["parameters"] and not np.isnan(values[row, place])
            ]
            if stray:
                raise ValueError("%s states the parameter %s, which its kind does not" % (where, stray[0]))
            result["action_option"].append(option)
            result["action_kind"].append(list(target["actions"]).index(kinds[row]))
            result["action_actor"].append(self.actors[task][actors[row]])
            declared.append((where, task, action))
        arrays = dict(
            action_option=np.asarray(result["action_option"], np.int32).reshape(-1),
            action_kind=np.asarray(result["action_kind"], np.int16).reshape(-1),
            action_actor=np.asarray(result["action_actor"], np.int32).reshape(-1),
            action_values=values[order].reshape(-1, len(columns)),
        )
        LOG.debug("decided actions exit graph=%s actions=%d seconds=%.4f", self.name, len(order), time.perf_counter() - started)
        return arrays, declared, order

    def nothing(self, options, actions):
        started = time.perf_counter()
        counts = np.bincount(actions["action_option"], minlength=len(options["keys"]))
        for option, (task, key) in enumerate(zip(options["option_task"].tolist(), options["keys"])):
            idle = self.aims[self.tasks["task_kind"][task]]["nothing"]
            if (key == idle) != (counts[option] == 0):
                raise ValueError(
                    "the option %s of %s holds %d actions; the option that does nothing, %s, holds none and every "
                    "other option holds one at least" % (key, self.where(task), counts[option], idle)
                )
        LOG.debug("decided nothing exit options=%d seconds=%.4f", len(counts), time.perf_counter() - started)

    def roles(self, table, declared, inverse):
        started = time.perf_counter()
        owner = inverse[np.asarray(table.column("action").to_numpy(), np.int64)]
        found = {name: table.column(name).to_pylist() for name in ("role", "key", "relation", "to_key")}
        rows, pending = [], []
        for row in np.argsort(owner, kind="stable").tolist():
            action = int(owner[row])
            where, task, held = declared[action]
            names = list(held["roles"])
            if found["role"][row] not in held["roles"]:
                raise ValueError("%s names the role %s, which its kind does not state" % (where, found["role"][row]))
            role = held["roles"][found["role"][row]]
            inner = "the target %s of %s" % (found["role"][row], where)
            source, other, code = self.resolved(inner, task, role, found, row, pending, len(rows))
            rows.append((action, names.index(found["role"][row]), source, other, code))
        made = sorted(set(pending))
        for place, (kind, key) in enumerate(made):
            self.lookup[(kind, key)] = len(self.keys)
            self.keys.append(key)
            self.kinds.append(kind)
        rows = [
            (action, role, self.lookup[source] if type(source) is tuple else source, other, code)
            for action, role, source, other, code in rows
        ]
        rows.sort(key=lambda row: row[:2])
        stated = {action: [] for action in range(len(declared))}
        for action, role, *_ in rows:
            stated[action].append(role)
        for action, (where, _, held) in enumerate(declared):
            if stated[action] != list(range(len(held["roles"]))):
                raise ValueError("%s states every role of its kind, %s, once" % (where, ", ".join(held["roles"]) or "none"))
        result = {
            "role_" + name: np.asarray([row[place] for row in rows], dtype).reshape(-1)
            for place, (name, dtype) in enumerate(
                (("action", np.int32), ("name", np.int16), ("source", np.int32), ("target", np.int32), ("code", np.int16))
            )
        }
        LOG.debug("decided roles exit graph=%s roles=%d made=%d seconds=%.4f", self.name, len(rows), len(made), time.perf_counter() - started)
        return result

    def node(self, inner, kinds, key):
        started = time.perf_counter()
        found = [self.lookup[(code, key)] for code in kinds if (code, key) in self.lookup]
        if len(found) != 1:
            raise ValueError("%s names the node %s; the graph holds %d nodes of that key of its kinds" % (inner, key, len(found)))
        LOG.debug("decided node exit key=%s seconds=%.6f", key, time.perf_counter() - started)
        return found[0]

    def resolved(self, inner, task, role, found, row, pending, place):
        started = time.perf_counter()
        registry, key = self.registry, found["key"][row]
        kinds = [registry.kind(kind) for kind in role["kinds"]]
        if type(key) is not str:
            raise ValueError("%s states no key" % inner)
        edged = role["sort"] == "edge"
        if edged != (found["relation"][row] is not None) or edged != (found["to_key"][row] is not None):
            raise ValueError("%s states a relation and the key of a second node exactly when it names an edge" % inner)
        if role["sort"] == "new":
            known = self.lookup.get((kinds[0], key))
            if known is not None and self.first[known] <= self.tasks["task_time"][task]:
                raise ValueError(
                    "%s names as the element its action creates the node %s, which is observed at or before the "
                    "time of its decision" % (inner, key)
                )
            if known is None:
                pending.append((kinds[0], key))
            result = ((kinds[0], key) if known is None else known), -1, -1
            LOG.debug("decided resolved exit made=%s seconds=%.6f", known is None, time.perf_counter() - started)
            return result
        source = self.node(inner, kinds, key)
        if not edged:
            LOG.debug("decided resolved exit node seconds=%.6f", time.perf_counter() - started)
            return source, -1, -1
        relation = found["relation"][row]
        if relation not in registry.tables:
            raise ValueError("%s names the relation %s, which the schema does not state" % (inner, relation))
        code = registry.code(relation)
        edge = registry.by_code[code]
        pairs = {(registry.kind(first), registry.kind(second)) for first, second in edge.pairs}
        if edge.symmetric:
            pairs |= {(second, first) for first, second in pairs}
        ends = [second for first, second in pairs if first == self.kinds[source]]
        other = self.node(inner, sorted(set(ends)), found["to_key"][row])
        if edge.symmetric and self.kinds[source] == self.kinds[other] and source > other:
            source, other = other, source
        LOG.debug("decided resolved exit edge seconds=%.6f", time.perf_counter() - started)
        return source, other, code

    def followed(self, table, options, place):
        started = time.perf_counter()
        times, ended = self.tasks["task_time"], self.tasks["task_ended"]
        decided = set(options["option_task"].tolist())
        task, other = (place[np.asarray(table.column(name).to_numpy(), np.int64)].tolist() for name in ("task", "other"))
        rows = []
        for first, second, actor in zip(task, other, table.column("actor").to_pylist()):
            where = self.where(first) if first in decided else "the task %d of graph %s" % (self.tasks["task_key"][first], self.name)
            if first not in decided or second not in decided:
                raise ValueError("%s names as the next decision of an actor a task that is no decision, or is none" % where)
            if actor not in self.actors[first] or actor not in self.actors[second] or times[second] <= times[first]:
                raise ValueError(
                    "%s names as the next decision of the actor %s the decision %d, a later decision of that actor"
                    " it is not" % (where, actor, self.tasks["task_key"][second])
                )
            if ended[first] == 1:
                raise ValueError("%s ends its episode and names a next decision" % where)
            rows.append((first, self.actors[first][actor], second))
        rows.sort()
        if len({row[:2] for row in rows}) != len(rows):
            raise ValueError("a decision of graph %s names two next decisions of one actor" % self.name)
        result = {
            "next_" + name: np.asarray([row[place] for row in rows], np.int32).reshape(-1)
            for place, name in enumerate(("task", "actor", "other"))
        }
        LOG.debug("decided followed exit graph=%s links=%d seconds=%.4f", self.name, len(rows), time.perf_counter() - started)
        return result

    def together(self, table, options, place):
        started = time.perf_counter()
        times, decided = self.tasks["task_time"], set(options["option_task"].tolist())
        pairs = sorted(
            zip(*(place[np.asarray(table.column(name).to_numpy(), np.int64)].tolist() for name in ("task", "other")))
        )
        for first, second in pairs:
            where = self.where(first) if first in decided else "the task %d of graph %s" % (self.tasks["task_key"][first], self.name)
            if (
                first not in decided
                or second not in decided
                or first == second
                or times[first] != times[second]
                or set(self.actors[first]) & set(self.actors[second])
            ):
                raise ValueError(
                    "%s names as a decision of other actors taken at the same time the task %d, which is not one"
                    % (where, self.tasks["task_key"][second])
                )
        if len(set(pairs)) != len(pairs) or set(pairs) != {(second, first) for first, second in pairs}:
            raise ValueError(
                "the decisions of graph %s taken at the same time each name the other, once" % self.name
            )
        result = dict(
            concurrent_task=np.asarray([first for first, _ in pairs], np.int32).reshape(-1),
            concurrent_other=np.asarray([second for _, second in pairs], np.int32).reshape(-1),
        )
        LOG.debug("decided together exit graph=%s pairs=%d seconds=%.4f", self.name, len(pairs), time.perf_counter() - started)
        return result

    def episodes(self, options):
        started = time.perf_counter()
        decided = np.zeros(len(self.tasks["task_key"]), bool)
        decided[options["option_task"]] = True
        ended, discount = self.tasks["task_ended"], self.tasks["task_discount"]
        stray = np.flatnonzero(~decided & ((ended >= 0) | ~np.isnan(discount)))
        if len(stray):
            raise ValueError(
                "the task %d of graph %s states the end of an episode or a discount and states no decision"
                % (self.tasks["task_key"][stray[0]], self.name)
            )
        wrong = np.flatnonzero(decided & ~np.isnan(discount) & ~((discount >= 0) & (discount <= 1)))
        if len(wrong):
            raise ValueError("%s states a discount outside 0 and 1" % self.where(int(wrong[0])))
        LOG.debug("decided episodes exit graph=%s seconds=%.4f", self.name, time.perf_counter() - started)

    def aimed(self, aims, options, actions):
        started = time.perf_counter()
        count = len(self.tasks["task_key"])
        start = np.searchsorted(options["option_task"], np.arange(count + 1))
        counts = np.bincount(actions["action_option"], minlength=len(options["keys"]))
        task, place, part, chosen = (np.asarray(aims[name]) for name in ("task", "option", "part", "chosen"))
        result = np.full(len(task), -1, np.int64)
        for row in np.flatnonzero(self.deciding[task]).tolist():
            owner = int(task[row])
            where = "a point of the target of %s" % self.where(owner)
            if not 0 <= place[row] < start[owner + 1] - start[owner]:
                raise ValueError("%s names the option %d; the decision states %d" % (where, place[row], start[owner + 1] - start[owner]))
            option = int(start[owner] + place[row])
            if part[row] != WHOLE and not 0 <= part[row] < counts[option]:
                raise ValueError("%s names the action %d of the option %s, which holds %d" % (where, part[row], options["keys"][option], counts[option]))
            if bool(chosen[row]) != bool(options["option_chosen"][option]):
                raise ValueError("%s states whether its option %s was chosen other than the option does" % (where, options["keys"][option]))
            result[row] = option
        LOG.debug("decided aimed exit graph=%s points=%d seconds=%.4f", self.name, len(task), time.perf_counter() - started)
        return dict(target_option=result.astype(np.int32), target_part=np.where(result >= 0, part, -1).astype(np.int32))


def decided(registry, found, tasks, place, members, keys, kinds, seen, aims, name):
    started = time.perf_counter()
    held = Decided(registry, tasks, members, keys, kinds, seen, name)
    options, keyed, generators, order = held.options(found["option"], place)
    options["keys"] = keyed
    inverse = np.empty(len(order), np.int64)
    inverse[order] = np.arange(len(order))
    actions, declared, ordered = held.actions(found["action"], options, inverse)
    held.nothing(options, actions)
    placed = np.empty(len(ordered), np.int64)
    placed[ordered] = np.arange(len(ordered))
    roles = held.roles(found["role"], declared, placed)
    held.episodes(options)
    result = dict(
        **{name: values for name, values in options.items() if name != "keys"},
        **actions,
        **roles,
        **held.followed(found["next"], options, place),
        **held.together(found["concurrent"], options, place),
        **held.aimed(aims, options, actions),
    )
    LOG.info(
        "decided exit graph=%s options=%d actions=%d created=%d seconds=%.4f",
        name,
        len(keyed),
        len(actions["action_option"]),
        len(held.keys) - len(keys),
        time.perf_counter() - started,
    )
    return result, held.keys, np.asarray(held.kinds, np.int32), keyed, generators


def undecided(tasks, aims):
    started = time.perf_counter()
    count = len(aims["task"])
    result = dict(
        option_task=np.zeros(0, np.int32),
        option_sequence=np.zeros(0, bool),
        option_available=np.zeros(0, bool),
        option_chosen=np.zeros(0, bool),
        option_order=np.zeros(0, np.int32),
        option_generator=np.zeros(0, np.int32),
        option_seed=np.zeros(0, np.int64),
        option_shown=np.zeros(0, np.float64),
        option_logged=np.zeros(0, np.float64),
        option_drawn=np.zeros(0, np.float64),
        action_option=np.zeros(0, np.int32),
        action_kind=np.zeros(0, np.int16),
        action_actor=np.zeros(0, np.int32),
        action_values=np.zeros((0, 0), np.float32),
        role_action=np.zeros(0, np.int32),
        role_name=np.zeros(0, np.int16),
        role_source=np.zeros(0, np.int32),
        role_target=np.zeros(0, np.int32),
        role_code=np.zeros(0, np.int16),
        next_task=np.zeros(0, np.int32),
        next_actor=np.zeros(0, np.int32),
        next_other=np.zeros(0, np.int32),
        concurrent_task=np.zeros(0, np.int32),
        concurrent_other=np.zeros(0, np.int32),
        target_option=np.full(count, -1, np.int32),
        target_part=np.full(count, -1, np.int32),
    )
    LOG.debug("undecided exit tasks=%d seconds=%.4f", len(tasks["task_key"]), time.perf_counter() - started)
    return result
